#!/usr/bin/env node

// Generates webapp/src/manifest.ts from plugin.json and git state, so the
// plugin id/name/version have a single source of truth (plugin.json + git
// tags). With --print, only prints the computed version (used by the
// Makefile for the bundle name).

import {execSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const webappRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(webappRoot, '..');

function git(args) {
    return execSync(`git ${args}`, {cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore']}).trim();
}

function computeVersion(manifestVersion) {
    let described;
    try {
        described = git('describe --tags --dirty');
    } catch {
        // No tags yet (or shallow clone): fall back to a pseudo-version.
        return `${manifestVersion}+${git('rev-parse --short HEAD')}`;
    }

    // v1.1.0 -> 1.1.0
    // v1.1.0-2-g8072694 -> 1.1.0+2.g8072694 (semver build metadata)
    // v1.1.0-dirty -> 1.1.0+dirty
    const sameVersion = described.
        replace(/^v/, '').
        replace(/-(\d+)-g([0-9a-f]+)/, '+$1.$2').
        replace(/-dirty$/, (match, offset, str) => (str.includes('+') ? '.dirty' : '+dirty'));

    // If plugin.json has been bumped ahead of the latest tag (release
    // preparation), report that newer version with the same distance metadata.
    const tagVersion = described.replace(/^v/, '').split('-')[0];
    if (tagVersion === manifestVersion) {
        return sameVersion;
    }

    const distanceMatch = described.match(/-(\d+)-g([0-9a-f]+)/);
    const dirty = described.endsWith('-dirty') ? '.dirty' : '';
    const shortHash = git('rev-parse --short HEAD');
    const build = distanceMatch ? `${distanceMatch[1]}.${distanceMatch[2]}` : shortHash;
    return `${manifestVersion}+${build}${dirty}`;
}

function main() {
    const manifest = JSON.parse(readFileSync(join(repoRoot, 'plugin.json'), 'utf8'));
    const version = computeVersion(manifest.version);

    if (process.argv.includes('--print')) {
        process.stdout.write(`${version}\n`);
        return;
    }

    const content = `// This file is generated by scripts/sync-manifest.mjs (make apply).
// Do not edit by hand; version comes from plugin.json, with build metadata
// from git describe --tags --dirty.
export default {
    id: '${manifest.id}',
    name: '${manifest.name}',
    version: '${version}',
};
`;

    writeFileSync(join(webappRoot, 'src', 'manifest.ts'), content);
    process.stdout.write(`webapp/src/manifest.ts: ${manifest.id}@${version}\n`);
}

main();
